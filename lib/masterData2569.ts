/**
 * ดำเนินการ Batch Write เขียนข้อมูลราคากลางปี 2569 ลงใน Firestore คอลเลกชัน price_matrix
 * โดยใช้ Doc ID เป็น [หมวดหมู่]_[ชื่อรายการ]_[หน่วยนับ]
 */
export async function seedMasterPriceMatrix2569(dbInstance: Firestore): Promise<number> {
  const CHUNK_SIZE = 400; // Firestore จำกัดไม่เกิน 500 ops ต่อ 1 batch
  let totalCommitted = 0;

  for (let i = 0; i < MASTER_PRICE_MATRIX_2569.length; i += CHUNK_SIZE) {
    const chunk = MASTER_PRICE_MATRIX_2569.slice(i, i + CHUNK_SIZE);
    const batch = writeBatch(dbInstance);

    for (const item of chunk) {
      const docId = getMasterDocId(item.category, item.itemName, item.unit);
      const docRef = doc(dbInstance, "price_matrix", docId);

      batch.set(docRef, {
        itemName: item.itemName,
        category: item.category,
        maxPrice: item.maxPrice,
        unit: item.unit,
        condition: item.condition || null,
        note: item.note || "",
        updatedAt: serverTimestamp(),
      });

      totalCommitted++;
    }

    await batch.commit();
  }

  return totalCommitted;
}
