export interface MasterPriceItem {
  itemName: string;
  category: SutExpenseCategory;
  maxPrice: number;
  unit: string;
  condition?: "WEEKDAY" | "WEEKEND";
  note?: string;
}

/**
 * สร้าง Unique Document ID ในรูปแบบ [หมวดหมู่]_[ชื่อรายการ]_[หน่วยนับ]
 * มีการแปลงเครื่องหมาย '/' ในชื่อหรือหน่วยนับ (เช่น คน/วัน) เป็น '-' เพื่อป้องกัน Firestore Subcollection Path Error
 */
export function getMasterDocId(category: string, itemName: string, unit: string): string {
  const sanitize = (val: string) => (val || "").trim().replace(/\//g, "-");
  return `${sanitize(category)}_${sanitize(itemName)}_${sanitize(unit)}`;
}

